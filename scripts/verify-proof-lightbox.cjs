const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const source = fs.readFileSync('components/proof-image-lightbox.tsx', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
const moduleObject = { exports: {} };
vm.runInNewContext(compiled, { exports: moduleObject.exports, module: moduleObject, require: name => name.endsWith('.module.css') ? new Proxy({}, { get: (_, key) => String(key) }) : require(name) });
const { fitImageScale, clampImageScale, ProofImageLightbox } = moduleObject.exports;
assert.equal(fitImageScale({ width: 1000, height: 2000 }, { width: 1000, height: 500 }), .25);
assert.equal(fitImageScale({ width: 3200, height: 900 }, { width: 800, height: 600 }), .25);
assert.equal(fitImageScale({ width: 330, height: 645 }, { width: 1280, height: 900 }), 1);
assert.equal(fitImageScale({ width: 0, height: 0 }, { width: 390, height: 600 }), 1);
assert.equal(fitImageScale({ width: Infinity, height: 900 }, { width: 390, height: 600 }), 1);
assert.equal(clampImageScale(.001), .05); assert.equal(clampImageScale(99), 8);
assert.equal(clampImageScale(NaN), 1); assert.equal(clampImageScale(Infinity), 1); assert.equal(clampImageScale(.75), .75);
const markup = renderToStaticMarkup(React.createElement(ProofImageLightbox, { image: { src: '/api/reporting/proof-image?fixture=1', title: '검증 지면', description: '자료상 게재 확인' }, onClose() {} }));
for (const label of ['게재 이미지 전체 화면', '이미지 닫기', '확대', '축소', '원본 크기', '화면에 맞춤', '확대 이미지']) assert.ok(markup.includes(label), label);
assert.ok(!/fetch\(|localStorage|sessionStorage/.test(source), 'Viewer must not save or change report data');
const page = fs.readFileSync('app/(dashboard)/creative/page.tsx', 'utf8');
assert.ok(page.includes('setEditor(null); setUploadError(""); setLightboxImage(null);'), 'Scope changes clear the viewer');
assert.ok(page.includes('onDrop=') && page.includes('onPaste='), 'Drop/paste registration remains');
assert.ok(page.includes('className={styles.imageOpenButton}'), 'Viewer uses its own button, not the upload label');
console.log('Proof lightbox checks passed: scaling, limits, SSR, accessibility labels, read-only viewing and scope cleanup.');
